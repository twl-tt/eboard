const JYUTPING_DICT = new Map<string, string>(PAIRS)

export function toJyutpingChar(ch: string): string | null {
  return JYUTPING_DICT.get(ch) ?? null
}

export function hasJyutpingCoverage(text: string): number {
  const chars = [...text].filter((c) => /[\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff]/.test(c))
  if (chars.length === 0) return 1
  const hit = chars.filter((c) => JYUTPING_DICT.has(c)).length
  return hit / chars.length
}
